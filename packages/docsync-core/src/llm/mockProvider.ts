import { LLMProvider } from "../types";

/**
 * Deterministic, offline, zero-cost LLM provider used by the entire automated test suite and as a
 * safe default when no real provider is configured for local/manual runs. It performs a
 * best-effort templated rewrite rather than real generation — explicitly NOT meant to be
 * mistaken for AI-quality output (the CLI/extension label suggestions from this provider as
 * "detection-only template", see `suggestionEngine.ts`).
 */
export class MockLLMProvider implements LLMProvider {
  name = "mock";

  async generate(prompt: string): Promise<string> {
    const signatureLine = prompt
      .split("\n")
      .find((line) => line.startsWith("Current signature:"));
    const signature = signatureLine?.replace("Current signature:", "").trim() ?? "(unknown signature)";
    return `Updated documentation for ${signature}. (generated by mock provider — review before accepting)`;
  }
}
